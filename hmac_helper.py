import base64
import hashlib
import hmac
import logging as log


class HmacHelper:
    """
    Helper for API Key + HMAC-SHA256 authentication, used by the Partner Merchant Onboarding APIs.

    Each request carries two headers:
     -> x-gl-auth : your static API Key (from the PayGlocal Partner Dashboard)
     -> x-gl-digest : Base64(HmacSHA256(signing_input, API_SECRET)), generated by create_digest

    This helper only generates the digest. Adding the headers to the request is left to the caller.
    """

    HMAC_ALGORITHM = "HmacSHA256"
    GET_METHOD = "GET"

    def get_signing_input(self, http_method, request_uri, payload):
        """
        Function to select the input that has to be signed
        :param http_method: HTTP method of the request (GET, POST, PUT)
        :param request_uri: request URI path, including the query string if present (no host or scheme)
         e.g. /gcc/v2/partner/merchant/onboard/business-category
        :param payload: exact raw request body (json stringified), as sent on the wire

        Signing input rules
         -> GET : request URI path (including query string if present)
         -> POST / PUT : exact raw request body

        :return: signing input
        """
        if http_method is not None and http_method.upper() == self.GET_METHOD:
            return request_uri
        return payload

    def create_digest(self, http_method, request_uri, payload, api_secret):
        """
        Function to create the digest for the x-gl-digest header
        :param http_method: HTTP method of the request (GET, POST, PUT)
        :param request_uri: request URI path, including the query string if present (used for GET)
        :param payload: exact raw request body (json stringified), used for POST / PUT. Compute the digest
         over the same string you send as the body, any difference in whitespace or field order fails with 401
        :param api_secret: API Secret of the partner (Downloaded from the PayGlocal Partner Dashboard), never the API Key

        :return: Base64 encoded HmacSHA256 digest
        """
        if api_secret is None or api_secret == '':
            log.error("Partner API secret is null.")
            return None

        signing_input = self.get_signing_input(http_method, request_uri, payload)
        if signing_input is None:
            log.error("Signing input is null. Pass request_uri for GET and payload for POST / PUT.")
            return None

        log.info('Creating ' + self.HMAC_ALGORITHM + ' digest for ' + str(http_method) + ' request')
        hmac_digest = hmac.new(api_secret.encode('utf-8'), signing_input.encode('utf-8'), hashlib.sha256).digest()
        return base64.b64encode(hmac_digest).decode('utf-8')
